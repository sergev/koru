# What a codepoint with no glyph draws: U+FFFD's box, and it fills the cell so
# that "this is not in the font" is never mistaken for a space.
REPLACEMENT = ["#####", "# # #", "## ##", "# # #", "#####", "     ", "     "]


def rows(art):
    """Seven row bytes, low bit leftmost, in an 8-wide cell."""
    out = []
    for line in art:
        if len(line) != 5:
            raise SystemExit("a glyph row is not five columns: %r" % line)
        bits = 0
        for x, c in enumerate(line):
            if c == '#':
                bits |= 1 << x
            elif c != ' ':
                raise SystemExit("a glyph row has %r in it" % c)
        out.append(bits)
    out.append(0)  # the eighth row is the spacing below
    return out


def main():
    missing = [chr(c) for c in range(0x20, 0x7f) if chr(c) not in ART]
    if missing:
        raise SystemExit("no art for: %r" % missing)

    w = sys.stdout.write
    w("// SPDX-License-Identifier: MIT\n")
    w("//\n")
    w("// Generated by screen/tools/mkfont.py. Do not edit: edit the glyph art\n")
    w("// there and re-run it. The font is authored for this repository.\n")
    w("//\n")
    w("// One glyph is eight rows of eight bits, low bit leftmost. The art is 5x7\n")
    w("// inside that, which leaves the spacing a terminal cell needs.\n")
    w("#pragma once\n\n")
    w("#include <cstdint>\n\n")
    w("#define KS_FONT_W 8\n")
    w("#define KS_FONT_H 8\n")
    w("#define KS_FONT_FIRST 0x20\n")
    w("#define KS_FONT_LAST 0x7e\n\n")
    w("// ASCII 0x20 through 0x7e, in order.\n")
    w("static const uint8_t KS_FONT[KS_FONT_LAST - KS_FONT_FIRST + 1][KS_FONT_H] = {\n")
    for c in range(0x20, 0x7f):
        ch = chr(c)
        body = ", ".join("0x%02x" % b for b in rows(ART[ch]))
        # A trailing backslash would splice the comment into the next line.
        label = {' ': "space", '\\': "backslash"}.get(ch, ch)
        w("    { %s }, // %s\n" % (body, label))
    w("};\n\n")
    w("// What a codepoint outside the font draws: U+FFFD's box.\n")
    w("static const uint8_t KS_FONT_MISSING[KS_FONT_H] = { %s };\n"
      % ", ".join("0x%02x" % b for b in rows(REPLACEMENT)))


if __name__ == "__main__":
    main()
